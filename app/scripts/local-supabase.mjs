import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";
import { requireLoopbackSupabaseApiUrl } from "./local-supabase-safety.mjs";
import {
  ensureLocalAcceptanceDataset,
  localAcceptanceFan,
  localPhase5AcceptanceAccounts,
  localPhase5AcceptanceFixtureMetadataKey,
  localPhase5AcceptanceFixtureVersion,
} from "./local-acceptance-fixtures.mjs";

const appDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryDirectory = resolve(appDirectory, "..");
const localEnvironmentPath = resolve(appDirectory, ".env.development.local");
const supabaseCliPath = resolve(appDirectory, "node_modules/supabase/dist/supabase.js");
const action = process.argv[2];

function runSupabase(arguments_) {
  const result = spawnSync(process.execPath, [supabaseCliPath, ...arguments_, "--workdir", repositoryDirectory], {
    cwd: appDirectory,
    encoding: "utf8",
    maxBuffer: 20 * 1024 * 1024,
    env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: "1" },
  });

  if (result.error) throw new Error(`Could not run the pinned Supabase CLI: ${result.error.message}`);
  if (result.status !== 0) {
    const detail = redact([result.stdout, result.stderr].filter(Boolean).join("\n") || "Supabase CLI failed.");
    throw new Error(detail.trim());
  }
  return result.stdout;
}

function redact(value) {
  return value
    .replace(/\u001b\[[0-9;]*m/g, "")
    .replace(/^.*(?:SECRET|SERVICE_ROLE|ANON|PUBLISHABLE)_KEY.*$/gim, "[Supabase key omitted]")
    .replace(/postgres(?:ql)?:\/\/\S+/gi, "[database URL omitted]")
    .replace(/eyJ[A-Za-z0-9._-]+/g, "[JWT omitted]")
    .replace(/sb_(?:publishable|secret)_[A-Za-z0-9_-]+/g, "[Supabase key omitted]");
}

function parseEnvironment(output) {
  const values = new Map();
  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(?:"([^"]*)"|'([^']*)'|(.*))$/);
    if (match) values.set(match[1], (match[2] ?? match[3] ?? match[4] ?? "").trim());
  }
  return values;
}

function localStatus() {
  return parseEnvironment(runSupabase(["status", "-o", "env"]));
}

function refreshLocalEnvironment() {
  const status = localStatus();
  const publicKey = status.get("PUBLISHABLE_KEY") ?? status.get("ANON_KEY");
  if (!publicKey) throw new Error("The local Supabase stack did not report a browser-safe public key.");

  writeFileSync(
    localEnvironmentPath,
    [
      "# Generated by npm run backend:start/reset. Do not edit or commit.",
      "VITE_SUPABASE_URL=/supabase",
      `VITE_SUPABASE_PUBLISHABLE_KEY=${publicKey}`,
      "VITE_SUPABASE_BACKEND=local",
      "VITE_ALLOW_HOSTED_SUPABASE_DEV=false",
      "",
    ].join("\n"),
    { mode: 0o600 },
  );
  return status;
}

function printSafeStatus(status) {
  const apiUrl = status.get("API_URL") ?? "http://127.0.0.1:15421";
  const studioUrl = status.get("STUDIO_URL") ?? "http://127.0.0.1:15423";
  const mailUrl = status.get("INBUCKET_URL") ?? status.get("MAILPIT_URL") ?? "http://127.0.0.1:15424";
  console.log("FANatical local Supabase is ready.");
  console.log(`API (Vite proxy target): ${apiUrl}`);
  console.log(`Studio: ${studioUrl}`);
  console.log(`Local email inbox: ${mailUrl}`);
  console.log("Browser credentials were refreshed in .env.development.local (values hidden).");
}

function localClient(url, key) {
  return createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
  });
}

function runLocalSql(sql) {
  const result = spawnSync(
    "docker",
    ["exec", "-i", "supabase_db_fanatical-local", "psql", "-U", "postgres", "-d", "postgres", "-At", "-v", "ON_ERROR_STOP=1", "-c", sql],
    {
      cwd: repositoryDirectory,
      encoding: "utf8",
      maxBuffer: 2 * 1024 * 1024,
    },
  );
  if (result.error) throw new Error(`Could not run loopback-only fixture bootstrap SQL: ${result.error.message}`);
  if (result.status !== 0) {
    const detail = redact([result.stdout, result.stderr].filter(Boolean).join("\n") || "Local fixture bootstrap SQL failed.");
    throw new Error(detail.trim());
  }
  return result.stdout.trim();
}

function requireUuid(value) {
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)) {
    throw new Error("The local acceptance fan has an invalid user ID.");
  }
  return value;
}

function escapeSqlString(value) {
  return String(value).replaceAll("'", "''");
}

function removeTemporaryFixtureAuthority(userIdValue) {
  const userId = requireUuid(userIdValue);
  runLocalSql(`do $fixture$ begin delete from public.staff_roles where user_id = '${userId}'::uuid; if exists (select 1 from public.staff_roles where user_id = '${userId}'::uuid) then raise exception 'Temporary fixture authority was not removed'; end if; end $fixture$;`);
}

function removeAcceptanceFixtureAuthorityResidue() {
  const email = localAcceptanceFan.email.replaceAll("'", "''");
  runLocalSql(`do $fixture$ begin delete from public.staff_roles where user_id in (select id from auth.users where lower(email) = lower('${email}')); if exists (select 1 from public.staff_roles role join auth.users auth_user on auth_user.id = role.user_id where lower(auth_user.email) = lower('${email}')) then raise exception 'Acceptance fixture authority residue was not removed'; end if; end $fixture$;`);
}

function grantTemporaryFixtureAuthority(userIdValue) {
  const userId = requireUuid(userIdValue);
  runLocalSql(`do $fixture$ begin if exists (select 1 from public.staff_roles where user_id = '${userId}'::uuid) then raise exception 'Stale fixture authority was not removed before grant'; end if; insert into public.staff_roles(user_id, role, permissions, is_active) values ('${userId}'::uuid, 'admin', array[]::text[], true); end $fixture$;`);
}

async function provisionLocalAcceptanceFan(status, { resetBaseline = false } = {}) {
  const apiUrl = requireLoopbackSupabaseApiUrl(status.get("API_URL"));
  const publicKey = status.get("PUBLISHABLE_KEY") ?? status.get("ANON_KEY");
  const serviceKey = status.get("SECRET_KEY") ?? status.get("SERVICE_ROLE_KEY");
  if (!publicKey || !serviceKey) throw new Error("Local Supabase did not report the keys needed for the acceptance fixture.");

  const admin = localClient(apiUrl, serviceKey);
  const listed = await admin.auth.admin.listUsers({ page: 1, perPage: 1000 });
  if (listed.error) throw new Error(`Could not inspect the local acceptance fan: ${listed.error.message}`);
  let existing = listed.data.users.find((candidate) => candidate.email?.toLowerCase() === localAcceptanceFan.email);

  if (resetBaseline && existing) {
    const removed = await admin.auth.admin.deleteUser(existing.id);
    if (removed.error) throw new Error(`Could not reset the local acceptance fan: ${removed.error.message}`);
    existing = undefined;
  }

  const fixtureResult = existing
    ? await admin.auth.admin.updateUserById(existing.id, {
        password: localAcceptanceFan.password,
        email_confirm: true,
        ban_duration: "none",
      })
    : await admin.auth.admin.createUser({
        email: localAcceptanceFan.email,
        password: localAcceptanceFan.password,
        email_confirm: true,
        user_metadata: { display_name: localAcceptanceFan.displayName },
      });
  if (fixtureResult.error) throw new Error(`Could not prepare the local acceptance fan: ${fixtureResult.error.message}`);

  await ensureLocalAcceptanceDataset({
    apiUrl,
    publicKey,
    serviceKey,
    userId: fixtureResult.data.user.id,
    removeTemporaryAuthority: removeTemporaryFixtureAuthority,
    grantTemporaryAuthority: grantTemporaryFixtureAuthority,
  });

  const verifier = localClient(apiUrl, publicKey);
  const verified = await verifier.auth.signInWithPassword({
    email: localAcceptanceFan.email,
    password: localAcceptanceFan.password,
  });
  if (verified.error || verified.data.user?.email !== localAcceptanceFan.email) {
    throw new Error(`Local acceptance fan password verification failed${verified.error ? `: ${verified.error.message}` : "."}`);
  }
  const signedOut = await verifier.auth.signOut();
  if (signedOut.error) throw new Error(`Could not close the local acceptance verification session: ${signedOut.error.message}`);
  console.log(`Local acceptance fan is ready: ${localAcceptanceFan.email}`);
}

async function ensureLocalAcceptanceFan(status, options = {}) {
  requireLoopbackSupabaseApiUrl(status.get("API_URL"));
  removeAcceptanceFixtureAuthorityResidue();
  try {
    return await provisionLocalAcceptanceFan(status, options);
  } finally {
    removeAcceptanceFixtureAuthorityResidue();
  }
}

async function callRpc(client, name, arguments_, label) {
  const result = await client.rpc(name, arguments_);
  if (result.error) throw new Error(`${label}: ${result.error.message}`);
  return result.data;
}

async function configurePhase5FanBaseline({
  account,
  apiUrl,
  publicKey,
  userId,
}) {
  const client = localClient(apiUrl, publicKey);
  const anonymous = localClient(apiUrl, publicKey);
  const signedIn = await client.auth.signInWithPassword({
    email: account.email,
    password: account.password,
  });
  if (signedIn.error || signedIn.data.user?.id !== userId) {
    throw new Error(`Could not authenticate ${account.displayName} for local Phase 5A setup${signedIn.error ? `: ${signedIn.error.message}` : "."}`);
  }

  try {
    await callRpc(client, "set_my_fanatical_name", {
      fanatical_name_value: account.fanaticalName,
    }, `Could not set ${account.displayName}'s Fanatical Name`);
    await callRpc(client, "set_my_profile_privacy", {
      visibility_value: account.visibility,
      personal_field_visibility_value: {},
    }, `Could not set ${account.displayName}'s profile privacy`);
    await callRpc(client, "replace_my_followed_teams", {
      team_ids: [...account.followedTeamIds],
    }, `Could not set ${account.displayName}'s followed Teams`);

    const universe = await callRpc(
      anonymous,
      "get_news_demo_universe",
      {},
      `Could not load the governed Demo identities for ${account.displayName}`,
    );
    const currentFollowing = await callRpc(
      client,
      "get_my_news_following",
      {},
      `Could not inspect ${account.displayName}'s existing News Following`,
    );
    for (const identity of universe ?? []) {
      const existing = currentFollowing?.find((follow) => (
        follow.target_type === identity.target_type && follow.target_id === identity.target_id
      ));
      const existingFollowId = existing?.follow_ids?.[0];
      if (existingFollowId) {
        await callRpc(client, "set_my_news_follow_scopes", {
          follow_id_value: existingFollowId,
          sport_scope_ids_value: [],
          team_scope_ids_value: [],
        }, `Could not normalize ${account.displayName}'s local News follow scopes`);
        await callRpc(client, "unmute_my_news_follow", {
          follow_id_value: existingFollowId,
        }, `Could not normalize ${account.displayName}'s local News follow mute state`);
      } else {
        await callRpc(client, "follow_news_identity", {
          target_type_value: identity.target_type,
          target_public_id_value: identity.target_id,
          sport_scope_ids_value: [],
          team_scope_ids_value: [],
        }, `Could not initialize ${account.displayName}'s News Following`);
      }
    }
  } finally {
    const signedOut = await client.auth.signOut();
    if (signedOut.error) {
      throw new Error(`Could not close ${account.displayName}'s local setup session: ${signedOut.error.message}`);
    }
  }
}

function ensurePhase5ModeratorAuthority(account, userIdValue) {
  const userId = requireUuid(userIdValue);
  const actorKey = escapeSqlString(account.operationalActorKey);
  const displayName = escapeSqlString(account.displayName);
  runLocalSql(`do $fixture$ begin insert into public.staff_roles(user_id, role, permissions, is_active) values ('${userId}'::uuid, 'admin', array['community_moderate', 'news_request_resolve']::text[], true) on conflict (user_id) do update set role = 'admin', permissions = array['community_moderate', 'news_request_resolve']::text[], is_active = true; insert into public.catalog_actors(actor_key, actor_type, auth_user_id, display_name, active) values ('${actorKey}', 'service', '${userId}'::uuid, '${displayName}', true) on conflict (actor_key) do update set actor_type = 'service', auth_user_id = excluded.auth_user_id, display_name = excluded.display_name, active = true; end $fixture$;`);
}

async function ensurePhase5AcceptanceAccounts(status, { resetBaseline = false } = {}) {
  const apiUrl = requireLoopbackSupabaseApiUrl(status.get("API_URL"));
  const publicKey = status.get("PUBLISHABLE_KEY") ?? status.get("ANON_KEY");
  const serviceKey = status.get("SECRET_KEY") ?? status.get("SERVICE_ROLE_KEY");
  if (!publicKey || !serviceKey) {
    throw new Error("Local Supabase did not report the keys needed for Phase 5A acceptance accounts.");
  }

  const admin = localClient(apiUrl, serviceKey);
  const listed = await admin.auth.admin.listUsers({ page: 1, perPage: 1000 });
  if (listed.error) throw new Error(`Could not inspect the local Phase 5A accounts: ${listed.error.message}`);
  const usersByEmail = new Map(
    listed.data.users
      .filter((candidate) => candidate.email)
      .map((candidate) => [candidate.email.toLowerCase(), candidate]),
  );

  for (const account of localPhase5AcceptanceAccounts) {
    let existing = usersByEmail.get(account.email.toLowerCase());
    if (resetBaseline && existing) {
      const removed = await admin.auth.admin.deleteUser(existing.id);
      if (removed.error) throw new Error(`Could not reset ${account.displayName}: ${removed.error.message}`);
      existing = undefined;
    }

    const prepared = existing
      ? await admin.auth.admin.updateUserById(existing.id, {
          password: account.password,
          email_confirm: true,
          ban_duration: "none",
          user_metadata: { display_name: account.displayName },
        })
      : await admin.auth.admin.createUser({
          email: account.email,
          password: account.password,
          email_confirm: true,
          user_metadata: { display_name: account.displayName },
        });
    if (prepared.error) {
      throw new Error(`Could not prepare ${account.displayName}: ${prepared.error.message}`);
    }

    const userId = prepared.data.user.id;
    const requiresBaseline = prepared.data.user.app_metadata?.[localPhase5AcceptanceFixtureMetadataKey]
      !== localPhase5AcceptanceFixtureVersion;
    if (account.operationalActorKey) {
      ensurePhase5ModeratorAuthority(account, userId);
    } else if (requiresBaseline || resetBaseline) {
      await configurePhase5FanBaseline({ account, apiUrl, publicKey, userId });
      const marked = await admin.auth.admin.updateUserById(userId, {
        app_metadata: {
          ...prepared.data.user.app_metadata,
          [localPhase5AcceptanceFixtureMetadataKey]: localPhase5AcceptanceFixtureVersion,
        },
      });
      if (marked.error) {
        throw new Error(`Could not mark ${account.displayName}'s completed local Phase 5A baseline: ${marked.error.message}`);
      }
    }
  }

  console.log("Phase 5A acceptance accounts are ready: Brad, Test Fan, and Moderator.");
}

function runSqlTests() {
  const testsDirectory = resolve(repositoryDirectory, "supabase/tests");
  const testFiles = readdirSync(testsDirectory)
    .filter((fileName) => fileName.endsWith(".sql"))
    .sort();

  if (testFiles.length === 0) throw new Error("No Supabase SQL tests were found.");

  for (const testFile of testFiles) {
    const testPath = resolve(testsDirectory, testFile);
    const result = spawnSync(
      "docker",
      ["exec", "-i", "supabase_db_fanatical-local", "psql", "-U", "postgres", "-d", "postgres", "-v", "ON_ERROR_STOP=1", "-f", "-"],
      {
        cwd: repositoryDirectory,
        encoding: "utf8",
        input: readFileSync(testPath, "utf8"),
        maxBuffer: 20 * 1024 * 1024,
      },
    );

    if (result.error) throw new Error(`Could not run ${testFile}: ${result.error.message}`);
    if (result.status !== 0) {
      const detail = redact([result.stdout, result.stderr].filter(Boolean).join("\n") || "SQL test failed.");
      throw new Error(`${testFile} failed:\n${detail.trim()}`);
    }
    console.log(`Passed ${testFile}`);
  }
}

try {
  if (action === "start") {
    runSupabase(["start"]);
    const status = refreshLocalEnvironment();
    await ensureLocalAcceptanceFan(status);
    await ensurePhase5AcceptanceAccounts(status);
    printSafeStatus(status);
  } else if (action === "stop") {
    runSupabase(["stop"]);
    console.log("FANatical local Supabase stopped. Local data was preserved.");
  } else if (action === "reset") {
    runSupabase(["db", "reset", "--local"]);
    const status = refreshLocalEnvironment();
    await ensureLocalAcceptanceFan(status, { resetBaseline: true });
    await ensurePhase5AcceptanceAccounts(status, { resetBaseline: true });
    printSafeStatus(status);
    console.log("The local database was rebuilt from every repository migration.");
  } else if (action === "status") {
    printSafeStatus(refreshLocalEnvironment());
  } else if (action === "test") {
    runSqlTests();
    console.log("All local Supabase SQL tests passed.");
  } else {
    throw new Error("Usage: node scripts/local-supabase.mjs <start|stop|reset|status|test>");
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
