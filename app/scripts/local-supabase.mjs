import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryDirectory = resolve(appDirectory, "..");
const localEnvironmentPath = resolve(appDirectory, ".env.development.local");
const supabaseCliPath = resolve(appDirectory, "node_modules/supabase/dist/supabase.js");
const action = process.argv[2];

function runSupabase(arguments_) {
  const result = spawnSync(process.execPath, [supabaseCliPath, ...arguments_, "--workdir", repositoryDirectory], {
    cwd: appDirectory,
    encoding: "utf8",
    maxBuffer: 20 * 1024 * 1024,
    env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: "1" },
  });

  if (result.error) throw new Error(`Could not run the pinned Supabase CLI: ${result.error.message}`);
  if (result.status !== 0) {
    const detail = redact([result.stdout, result.stderr].filter(Boolean).join("\n") || "Supabase CLI failed.");
    throw new Error(detail.trim());
  }
  return result.stdout;
}

function redact(value) {
  return value
    .replace(/\u001b\[[0-9;]*m/g, "")
    .replace(/^.*(?:SECRET|SERVICE_ROLE|ANON|PUBLISHABLE)_KEY.*$/gim, "[Supabase key omitted]")
    .replace(/postgres(?:ql)?:\/\/\S+/gi, "[database URL omitted]")
    .replace(/eyJ[A-Za-z0-9._-]+/g, "[JWT omitted]")
    .replace(/sb_(?:publishable|secret)_[A-Za-z0-9_-]+/g, "[Supabase key omitted]");
}

function parseEnvironment(output) {
  const values = new Map();
  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(?:"([^"]*)"|'([^']*)'|(.*))$/);
    if (match) values.set(match[1], (match[2] ?? match[3] ?? match[4] ?? "").trim());
  }
  return values;
}

function localStatus() {
  return parseEnvironment(runSupabase(["status", "-o", "env"]));
}

function refreshLocalEnvironment() {
  const status = localStatus();
  const publicKey = status.get("PUBLISHABLE_KEY") ?? status.get("ANON_KEY");
  if (!publicKey) throw new Error("The local Supabase stack did not report a browser-safe public key.");

  writeFileSync(
    localEnvironmentPath,
    [
      "# Generated by npm run backend:start/reset. Do not edit or commit.",
      "VITE_SUPABASE_URL=/supabase",
      `VITE_SUPABASE_PUBLISHABLE_KEY=${publicKey}`,
      "VITE_SUPABASE_BACKEND=local",
      "VITE_ALLOW_HOSTED_SUPABASE_DEV=false",
      "",
    ].join("\n"),
    { mode: 0o600 },
  );
  return status;
}

function printSafeStatus(status) {
  const apiUrl = status.get("API_URL") ?? "http://127.0.0.1:15421";
  const studioUrl = status.get("STUDIO_URL") ?? "http://127.0.0.1:15423";
  const mailUrl = status.get("INBUCKET_URL") ?? status.get("MAILPIT_URL") ?? "http://127.0.0.1:15424";
  console.log("FANatical local Supabase is ready.");
  console.log(`API (Vite proxy target): ${apiUrl}`);
  console.log(`Studio: ${studioUrl}`);
  console.log(`Local email inbox: ${mailUrl}`);
  console.log("Browser credentials were refreshed in .env.development.local (values hidden).");
}

function runSqlTests() {
  const testsDirectory = resolve(repositoryDirectory, "supabase/tests");
  const testFiles = readdirSync(testsDirectory)
    .filter((fileName) => fileName.endsWith(".sql"))
    .sort();

  if (testFiles.length === 0) throw new Error("No Supabase SQL tests were found.");

  for (const testFile of testFiles) {
    const testPath = resolve(testsDirectory, testFile);
    const result = spawnSync(
      "docker",
      ["exec", "-i", "supabase_db_fanatical-local", "psql", "-U", "postgres", "-d", "postgres", "-v", "ON_ERROR_STOP=1", "-f", "-"],
      {
        cwd: repositoryDirectory,
        encoding: "utf8",
        input: readFileSync(testPath, "utf8"),
        maxBuffer: 20 * 1024 * 1024,
      },
    );

    if (result.error) throw new Error(`Could not run ${testFile}: ${result.error.message}`);
    if (result.status !== 0) {
      const detail = redact([result.stdout, result.stderr].filter(Boolean).join("\n") || "SQL test failed.");
      throw new Error(`${testFile} failed:\n${detail.trim()}`);
    }
    console.log(`Passed ${testFile}`);
  }
}

try {
  if (action === "start") {
    runSupabase(["start"]);
    printSafeStatus(refreshLocalEnvironment());
  } else if (action === "stop") {
    runSupabase(["stop"]);
    console.log("FANatical local Supabase stopped. Local data was preserved.");
  } else if (action === "reset") {
    runSupabase(["db", "reset", "--local"]);
    printSafeStatus(refreshLocalEnvironment());
    console.log("The local database was rebuilt from every repository migration.");
  } else if (action === "status") {
    printSafeStatus(refreshLocalEnvironment());
  } else if (action === "test") {
    runSqlTests();
    console.log("All local Supabase SQL tests passed.");
  } else {
    throw new Error("Usage: node scripts/local-supabase.mjs <start|stop|reset|status|test>");
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
